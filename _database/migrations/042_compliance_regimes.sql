-- ============================================================================
-- 🏗️ CREATE COMPLIANCE REGIMES TABLE
-- ============================================================================
-- 🌍 One row per regime. ALL jurisdiction VALUES live here, never in PHP.
-- See the migration header for why every seeded row below ships with its
-- value columns NULL and isActive = 0 / isDraft = 1.
-- ============================================================================

CREATE TABLE IF NOT EXISTS `tblComplianceRegimes` (
    `regimeID`              SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `regimeCode`            VARCHAR(16) NOT NULL
        COMMENT 'Stable short code, e.g. GDPR, UK_GDPR, CCPA, CPRA, LGPD — the ONLY place a regime name may appear as literal DATA (never in PHP logic)',
    `displayName`           VARCHAR(128) NOT NULL
        COMMENT 'Human-readable regime name, e.g. "General Data Protection Regulation"',
    `jurisdiction`          VARCHAR(64) NULL DEFAULT NULL
        COMMENT 'Country/region label — descriptive, user-editable',
    `dsarSlaDays`           SMALLINT UNSIGNED NULL DEFAULT NULL
        COMMENT 'DSAR fulfilment SLA in days — USER/LEGAL-SUPPLIED, ships NULL',
    `dsarExtensionDays`     SMALLINT UNSIGNED NULL DEFAULT NULL
        COMMENT 'Permitted SLA extension where the regime allows one — USER/LEGAL-SUPPLIED, ships NULL',
    `breachNotifyHours`     SMALLINT UNSIGNED NULL DEFAULT NULL
        COMMENT 'Breach notification window to the supervisory authority, in hours — USER/LEGAL-SUPPLIED, ships NULL',
    `breachNotifyAuthority` VARCHAR(255) NULL DEFAULT NULL
        COMMENT 'Supervisory authority name/contact for breach notification — USER/LEGAL-SUPPLIED, ships NULL',
    `minAge`                TINYINT UNSIGNED NULL DEFAULT NULL
        COMMENT 'Digital-consent minimum age threshold — USER/LEGAL-SUPPLIED, ships NULL',
    `honorsGPC`             TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Does this regime treat Global Privacy Control as a valid opt-out signal — ships 0 (unconfirmed) for every seed row',
    `requiresDoNotSell`     TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Does this regime require a "Do Not Sell/Share" mechanism — ships 0 (unconfirmed) for every seed row',
    `lawfulBasisRequired`   TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'Does this regime require a recorded lawful basis per processing activity (GDPR-style) — ships 0 (unconfirmed) for every seed row',
    `isActive`              TINYINT(1) NOT NULL DEFAULT 0
        COMMENT 'OFF by default for every regime — an operator activates only after legal review; RegimeResolver NEVER returns an inactive regime',
    `isDraft`               TINYINT(1) NOT NULL DEFAULT 1
        COMMENT 'ON by default for every seed row — values are placeholders pending legal confirmation',
    `notes`                 TEXT NULL DEFAULT NULL
        COMMENT 'Free-text notes; MAY include suggested public-anchor values labelled "confirm with legal" — never treated as authoritative by PHP',
    PRIMARY KEY (`regimeID`),
    UNIQUE KEY `uq_regime_code` (`regimeCode`),
    INDEX `idx_regime_active_draft` (`isActive`, `isDraft`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='One row per data-protection regime — the data-driven core of G-004 Layer 3';

-- ============================================================================
-- 🏗️ CREATE REGIME RIGHTS TABLE
-- ============================================================================
-- 🔗 Many-to-many: which DSAR rights a regime grants. `right` values MUST be
-- drawn from the SAME union DSARManager::VALID_REQUEST_TYPES mirrors from
-- tblDataSubjectRequests.requestType (migration 040): access|portability|
-- erasure|rectification|restriction|object|do_not_sell|withdraw_consent|
-- automated_decision_optout. No CHECK constraint is added (MySQL/MariaDB
-- portability + this migration's own "additive, no procs" house rule) —
-- RegimeResolver::rightsFor() and any future admin-CRUD validate against
-- that allowlist in PHP before writing a row.
-- ============================================================================

CREATE TABLE IF NOT EXISTS `tblRegimeRights` (
    `regimeID` SMALLINT UNSIGNED NOT NULL,
    `right`    VARCHAR(40) NOT NULL
        COMMENT 'One of DSARManager::VALID_REQUEST_TYPES — access|portability|erasure|rectification|restriction|object|do_not_sell|withdraw_consent|automated_decision_optout',
    PRIMARY KEY (`regimeID`, `right`),
    CONSTRAINT `fk_rr_regime` FOREIGN KEY (`regimeID`)
        REFERENCES `tblComplianceRegimes` (`regimeID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Which DSAR rights a regime grants (G-004 Layer 3)';

-- ============================================================================
-- 🏗️ CREATE REGIME DISCLOSURES TABLE
-- ============================================================================
-- 📜 Required disclosure sections per regime — drives future privacy-page
-- rendering. `title`/`body` are USER/LEGAL-SUPPLIED content and this
-- migration inserts ZERO rows into this table (nothing to seed — every
-- regime is a draft with no confirmed disclosure text yet).
-- ============================================================================

CREATE TABLE IF NOT EXISTS `tblRegimeDisclosures` (
    `disclosureID`  INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `regimeID`      SMALLINT UNSIGNED NOT NULL,
    `disclosureKey` VARCHAR(64) NOT NULL
        COMMENT 'Stable key identifying which disclosure section this is, e.g. "categories_collected", "third_party_sharing"',
    `title`         VARCHAR(255) NULL DEFAULT NULL
        COMMENT 'USER/LEGAL-SUPPLIED section heading — ships NULL',
    `body`          TEXT NULL DEFAULT NULL
        COMMENT 'USER/LEGAL-SUPPLIED disclosure text — ships NULL/empty; NEVER generated by migration or PHP',
    PRIMARY KEY (`disclosureID`),
    INDEX `idx_regime_disclosure_regime` (`regimeID`, `disclosureKey`),
    CONSTRAINT `fk_rd_regime` FOREIGN KEY (`regimeID`)
        REFERENCES `tblComplianceRegimes` (`regimeID`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Required disclosure sections per regime — content is user/legal-supplied (G-004 Layer 3)';

-- ============================================================================
-- 🏗️ CREATE REGIME RESOLUTION TABLE
-- ============================================================================
-- 🗺️ The rule table RegimeResolver::resolve() walks, ORDER BY priority ASC,
-- to decide which regime governs a given (userID, partnerID, countryHint).
--
-- ⚠️ DEVIATION FROM THE EARLIER SPEC DRAFT: `regimeID` here is NULLABLE and
-- carries NO foreign key (the spec draft sketched `NOT NULL` + an FK). This
-- is deliberate:
--   1. The seeded 'default' rule below MUST be able to express "there is no
--      specific regime for this catch-all — fall through to RegimeResolver's
--      synthetic most-protective PHP default" — that requires regimeID to be
--      NULL-able for at least that one row.
--   2. Omitting the FK means an admin (future cycle) can delete/deactivate a
--      regime without first hunting down every resolution rule that
--      references it — RegimeResolver::resolve() already treats "rule
--      matched but its target regime is not ACTIVE+non-draft" as "keep
--      walking lower-priority rules", so a dangling regimeID degrades safely
--      rather than needing referential-integrity enforcement at the DB layer.
--   3. Since every regime ships isActive=0 in this migration, resolution
--      falls through to the PHP default regardless of this table's
--      contents today — the seeded row below exists to document that the
--      default rule exists, not to change current behaviour.
-- ============================================================================

CREATE TABLE IF NOT EXISTS `tblRegimeResolution` (
    `ruleID`     INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `matchType`  ENUM('country','region','partner','default') NOT NULL
        COMMENT 'What kind of hint this rule matches against',
    `matchValue` VARCHAR(64) NULL DEFAULT NULL
        COMMENT 'ISO country code, region label, or partnerID (as a string) — NULL for matchType=default',
    `regimeID`   SMALLINT UNSIGNED NULL DEFAULT NULL
        COMMENT 'Target regime — NULLABLE, NO foreign key (see table comment above); NULL means "no specific regime, fall through to the PHP default"',
    `priority`   SMALLINT NOT NULL DEFAULT 100
        COMMENT 'Lower = evaluated first by RegimeResolver::resolve()',
    PRIMARY KEY (`ruleID`),
    INDEX `idx_resolution` (`matchType`, `matchValue`, `priority`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Resolution rules RegimeResolver walks to pick a governing regime (G-004 Layer 3)';

-- 🌱 Seed ONE catch-all default rule (lowest priority = evaluated last).
-- Idempotent guard: only insert if no matchType='default' rule exists yet,
-- since this table has no natural UNIQUE key to ON-DUPLICATE-KEY against
-- (an admin may legitimately want several 'default'-adjacent rows later,
-- but this migration's job is only to document that the default rule
-- exists at all — never clobber an admin's later edits).
INSERT INTO `tblRegimeResolution` (`matchType`, `matchValue`, `regimeID`, `priority`)
SELECT 'default', NULL, NULL, 9999
WHERE NOT EXISTS (
    SELECT 1 FROM `tblRegimeResolution` WHERE `matchType` = 'default'
);

