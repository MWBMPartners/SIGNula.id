-- 📝 Description:
--   The core that makes "18+ data-protection regimes without code sprawl"
--   true: every jurisdiction-specific number/right/threshold/window/
--   disclosure lives in these tables, never hardcoded in PHP. Creates:
--     - tblComplianceRegimes   : one row per regime (GDPR, CCPA, LGPD, ...).
--                                ALL legal VALUES (SLA days, min age, breach
--                                window, authority contact) are user/legal
--                                supplied — seeded here as NULL placeholders.
--     - tblRegimeRights        : which DSAR rights (tblDataSubjectRequests.
--                                requestType union) a regime grants.
--     - tblRegimeDisclosures   : required disclosure sections per regime —
--                                title/body ship EMPTY; body is USER/LEGAL
--                                content, never generated by this migration.
--     - tblRegimeResolution    : the rule table RegimeResolver walks
--                                (country/region/partner/default → regimeID)
--                                to decide which regime governs a request.
--   Plus ONE tblSettings row (privacy category) for the generic,
--   country-agnostic most-protective-default minimum age fallback that
--   RegimeResolver::minAgeFor() uses when no active regime resolves.
--
--   ⚠️ NO REGIME IS EVER AUTO-ACTIVATED BY THIS MIGRATION. Every one of the
--   19 seeded regimes ships `isActive = 0, isDraft = 1` with its
--   dsarSlaDays / dsarExtensionDays / breachNotifyHours /
--   breachNotifyAuthority / minAge value columns left NULL — these are
--   legal-judgement values that only an operator + counsel may confirm and
--   activate (a later admin-CRUD cycle, G-004 spec §4.3, is NOT built by
--   this migration). Well-known PUBLIC anchor numbers (e.g. "GDPR is
--   commonly cited as 30 days / 72 hours") are offered ONLY as free-text
--   *suggestions* inside the `notes` column, clearly labelled "confirm with
--   legal" — they are NEVER written into the actual value columns, and
--   nothing here treats them as authoritative. RegimeResolver (the PHP
--   class this migration exists to support) reads ROWS, never regime code
--   literals — adding a 19th/20th regime is a row insert, zero PHP edits.
--
--   The 4 boolean CHARACTERISTIC flags (`honorsGPC`, `requiresDoNotSell`,
--   `lawfulBasisRequired`, and by extension `isActive`) are ALSO left at
--   their safe table DEFAULT (0) for every seeded regime, for the identical
--   reason the numeric columns stay NULL: whether e.g. CCPA "requires"
--   Do-Not-Sell is itself a configuration decision this migration declines
--   to make on the operator's behalf while the row is still `isDraft = 1` —
--   the future admin-CRUD activation workflow is where an owner deliberately
--   sets these, informed by the `notes` suggestions below.
--
--   tblRegimeResolution.regimeID is declared NULLABLE, WITHOUT a foreign key
--   (deviates from the earlier spec draft's `NOT NULL` + FK sketch — see the
--   table's own comment block below for the justification: the seeded
--   'default' rule intentionally carries regimeID = NULL, since — with every
--   regime inactive — resolution is expected to fall through to
--   RegimeResolver's synthetic most-protective PHP default regardless of
--   this table's contents).
--
-- 🔗 Related: .dev-team/specs/G-004.md §4 (4.1-4.4 — Layer 3, the
--    data-driven regime configuration model), web/private_html/compliance/
--    RegimeResolver.php (the ONLY PHP that reads these tables),
--    _database/migrations/040_consent_and_dsar.sql (tblDataSubjectRequests.
--    regimeCode / dueDate — the retro-wired consumer of this resolver),
--    _database/migrations/041_consent_categories_and_policy_versions.sql
--    (tblConsentRecords.regimeCode — the other retro-wired consumer).
